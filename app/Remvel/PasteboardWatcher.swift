import AppKit

/// Polls `changeCount` (cheap) and hands new copies to the core.
/// Only reading the pasteboard happens on the main thread; preprocessing and storage do not.
final class PasteboardWatcher {
    var onIngest: (() -> Void)?

    private let pasteboard = NSPasteboard.general
    private var changeCount: Int
    private var timer: Timer?

    /// http://nspasteboard.org markers for passwords and generated content.
    private let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]
    private let keptTypes: Set<NSPasteboard.PasteboardType> = [.string, .html, .rtf, .png, .tiff, .fileURL]

    init() {
        changeCount = pasteboard.changeCount
    }

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            self?.poll()
        }
    }

    private func poll() {
        guard pasteboard.changeCount != changeCount else { return }
        changeCount = pasteboard.changeCount

        // TODO: multiple pasteboard items (several files) are reduced to the first one.
        guard let item = pasteboard.pasteboardItems?.first,
              Set(item.types).isDisjoint(with: ignoredTypes) else { return }

        let reps = item.types
            .filter(keptTypes.contains)
            .compactMap { type in item.data(forType: type).map { Rep(uti: type.rawValue, data: $0) } }
        guard !reps.isEmpty, !Self.isBlankText(reps) else { return }

        let app = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        let copiedAt = Int64(Date().timeIntervalSince1970 * 1000)
        Core.shared.run({ store in
            try store.ingest(capture: Preprocessor.capture(reps: reps, app: app, copiedAt: copiedAt))
        }) { [weak self] result in
            if case .failure(let error) = result {
                NSLog("Remvel: ingest failed: \(error)")
            }
            self?.onIngest?()
        }
    }

    private static func isBlankText(_ reps: [Rep]) -> Bool {
        guard reps.count == 1, reps[0].uti == NSPasteboard.PasteboardType.string.rawValue else { return false }
        return String(decoding: reps[0].data, as: UTF8.self).trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
    }
}
