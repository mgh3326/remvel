import AppKit

/// Polls `changeCount` (cheap) and hands new copies to the core.
/// Only reading the pasteboard happens on the main thread; preprocessing and storage do not.
final class PasteboardWatcher {
    /// Polling speeds up right after a copy and backs off when nothing changes, to save battery.
    static let fastInterval: TimeInterval = 0.2
    static let slowInterval: TimeInterval = 1.0
    static let idlePollsBeforeSlow = 10

    /// nspasteboard.org: the bundle id of the app that wrote the pasteboard.
    static let sourceType = NSPasteboard.PasteboardType("org.nspasteboard.source")
    /// Matches UTI_FILE_PATHS in the core: every copied path, one per line.
    static let filePathsUTI = "io.github.remvel.file-paths"

    var onIngest: (() -> Void)?

    private let pasteboard = NSPasteboard.general
    private let settings = Settings.shared
    private var changeCount: Int
    private var timer: Timer?
    private var idlePolls = 0

    /// http://nspasteboard.org markers for passwords and generated content.
    private let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]
    /// Universal Clipboard: the copy came from another device.
    private let remoteType = NSPasteboard.PasteboardType("com.apple.is-remote-clipboard")
    private let keptTypes: Set<NSPasteboard.PasteboardType> = [.string, .html, .rtf, .png, .tiff, .fileURL]

    init() {
        changeCount = pasteboard.changeCount
    }

    func start() {
        schedule(Self.fastInterval)
    }

    private func schedule(_ interval: TimeInterval) {
        timer?.invalidate()
        let timer = Timer(timeInterval: interval, repeats: true) { [weak self] _ in self?.poll() }
        timer.tolerance = interval * 0.25
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    private func poll() {
        guard pasteboard.changeCount != changeCount else {
            idlePolls += 1
            if idlePolls == Self.idlePollsBeforeSlow {
                schedule(Self.slowInterval)
            }
            return
        }
        changeCount = pasteboard.changeCount
        if idlePolls >= Self.idlePollsBeforeSlow {
            schedule(Self.fastInterval)
        }
        idlePolls = 0
        guard !settings.paused else { return }

        // Other items are dropped, except that every copied file's path is kept (see filePathsUTI).
        guard let item = pasteboard.pasteboardItems?.first else { return }
        let types = Set(item.types)
        guard types.isDisjoint(with: ignoredTypes),
              !(settings.ignoreRemoteClipboard && types.contains(remoteType)) else { return }

        // Apps that follow nspasteboard.org name themselves; otherwise the frontmost app is a good guess.
        // Remvel names itself on its own writes, and the paster already bumped that item.
        let app = pasteboard.string(forType: Self.sourceType)
            ?? NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        if let app, app == Bundle.main.bundleIdentifier || settings.ignoredApps.contains(app) { return }

        var reps = item.types
            .filter(keptTypes.contains)
            .compactMap { type in item.data(forType: type).map { Rep(uti: type.rawValue, data: $0) } }
        let files = types.contains(.fileURL)
            ? pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL] ?? []
            : []
        if !files.isEmpty {
            reps.append(Rep(uti: Self.filePathsUTI, data: Data(files.map(\.path).joined(separator: "\n").utf8)))
        }
        guard !reps.isEmpty, !Self.isBlankText(reps) else { return }

        let copiedAt = Int64(Date().timeIntervalSince1970 * 1000)
        let limit = Int64(settings.historyLimit)
        Core.shared.run({ store in
            let result = try store.ingest(capture: Preprocessor.capture(reps: reps, app: app, copiedAt: copiedAt))
            if limit > 0, store.count() > UInt64(limit) {
                _ = try store.trim(maxItems: limit)
            }
            return result
        }) { [weak self] result in
            switch result {
            case .success(let ingest) where !ingest.deduplicated && !files.isEmpty:
                self?.addThumbnail(id: ingest.id, file: files[0])
            case .failure(let error):
                NSLog("Remvel: ingest failed: \(error)")
            default:
                break
            }
            self?.onIngest?()
        }
    }

    /// Quick Look renders asynchronously, so the thumbnail is added after the item is stored.
    private func addThumbnail(id: Int64, file: URL) {
        Preprocessor.fileThumbnailPNG(file) { [weak self] png in
            guard let png else { return }
            Core.shared.run({ try $0.setThumbnail(id: id, png: png) }) { _ in self?.onIngest?() }
        }
    }

    private static func isBlankText(_ reps: [Rep]) -> Bool {
        guard reps.count == 1, reps[0].uti == NSPasteboard.PasteboardType.string.rawValue else { return false }
        return String(decoding: reps[0].data, as: UTF8.self).trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
    }
}
